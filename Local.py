import os
import sys
import re
import socket
import threading
import queue
import subprocess
import ctypes
import shutil
import urllib.request
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import tkinter as tk
from tkinter import scrolledtext

APP_DIR = Path(__file__).resolve().parent
DOMAINS_DIR = APP_DIR / "Domains"
HOSTS_FILE = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "drivers" / "etc" / "hosts"
MARKER = "# LocalNet-managed entry"
HTTP_PORT = 8000
DOMAIN_SUFFIX = "localnet"
DEFAULT_PAGE = """<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>{name}</title></head>
<body>
<h1>Welcome to {name}.{suffix}</h1>
<p>This page was generated by LocalNet.</p>
</body>
</html>
"""


def is_admin():
    try:
        return bool(ctypes.windll.shell32.IsUserAnAdmin())
    except Exception:
        return False


def validate_name(name):
    if not name or not isinstance(name, str):
        return None
    name = name.strip().lower()
    if name.endswith("." + DOMAIN_SUFFIX):
        name = name[: -(len(DOMAIN_SUFFIX) + 1)]
    if not re.fullmatch(r"[a-z0-9]([a-z0-9\-]{0,61}[a-z0-9])?", name):
        return None
    return name


def full_domain(name):
    return f"{name}.{DOMAIN_SUFFIX}"


class LogQueue:
    def __init__(self):
        self.q = queue.Queue()

    def put(self, msg):
        self.q.put(msg)

    def drain(self, widget):
        try:
            while True:
                msg = self.q.get_nowait()
                widget.configure(state="normal")
                widget.insert(tk.END, msg + "\n")
                widget.see(tk.END)
                widget.configure(state="disabled")
        except queue.Empty:
            pass


class SiteStore:
    def __init__(self):
        self.lock = threading.Lock()
        self.hosted = {}
        self.restricted = set()

    def add(self, name):
        with self.lock:
            self.hosted[name] = full_domain(name)
            self.restricted.discard(name)

    def restrict(self, name):
        with self.lock:
            if name in self.hosted:
                self.restricted.add(name)
                return True
            return False

    def is_restricted(self, name):
        with self.lock:
            return name in self.restricted

    def lookup(self, host_header):
        host = host_header.split(":")[0].strip().lower()
        if host.endswith("." + DOMAIN_SUFFIX):
            short = host[: -(len(DOMAIN_SUFFIX) + 1)]
            with self.lock:
                if short in self.hosted:
                    return short
        return None

    def list_hosted(self):
        with self.lock:
            return sorted(self.hosted.keys())

    def list_restricted(self):
        with self.lock:
            return sorted(self.restricted)


def ensure_domain_folder(name):
    d = DOMAINS_DIR / name
    d.mkdir(parents=True, exist_ok=True)
    index = d / "index.html"
    if not index.exists():
        index.write_text(DEFAULT_PAGE.format(name=name, suffix=DOMAIN_SUFFIX), encoding="utf-8")
    return d


class Handler(BaseHTTPRequestHandler):
    store = None
    log = None

    def log_message(self, fmt, *args):
        pass

    def do_GET(self):
        self._handle()

    def do_HEAD(self):
        self._handle(head=True)

    def _handle(self, head=False):
        host = self.headers.get("Host", "")
        name = self.store.lookup(host)
        if name is None:
            self._send(404, b"Unknown domain")
            return
        if self.store.is_restricted(name):
            self._send(403, b"Domain is restricted")
            return
        root = (DOMAINS_DIR / name).resolve()
        path = self.path.split("?", 1)[0].split("#", 1)[0]
        path = urllib.request.url2pathname(path)
        if path in ("", "/"):
            path = "/index.html"
        target = (root / path.lstrip("/")).resolve()
        try:
            target.relative_to(root)
        except ValueError:
            self._send(403, b"Forbidden")
            return
        if target.is_dir():
            target = target / "index.html"
        if not target.is_file():
            self._send(404, b"Not found")
            return
        try:
            data = target.read_bytes()
        except OSError:
            self._send(500, b"Read error")
            return
        ctype = self._guess_type(target)
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        if not head:
            try:
                self.wfile.write(data)
            except (BrokenPipeError, ConnectionResetError):
                pass

    def _guess_type(self, p):
        ext = p.suffix.lower()
        return {
            ".html": "text/html; charset=utf-8",
            ".htm": "text/html; charset=utf-8",
            ".css": "text/css; charset=utf-8",
            ".js": "application/javascript; charset=utf-8",
            ".json": "application/json",
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".gif": "image/gif",
            ".svg": "image/svg+xml",
            ".ico": "image/x-icon",
            ".txt": "text/plain; charset=utf-8",
            ".webp": "image/webp",
        }.get(ext, "application/octet-stream")

    def _send(self, code, body):
        if isinstance(body, str):
            body = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            pass


class Server:
    def __init__(self, store, log):
        self.store = store
        self.log = log
        self.httpd = None
        self.thread = None

    def running(self):
        return self.httpd is not None

    def start(self):
        if self.httpd:
            return True
        Handler.store = self.store
        Handler.log = self.log
        try:
            self.httpd = ThreadingHTTPServer(("0.0.0.0", HTTP_PORT), Handler)
        except OSError as e:
            self.log(f"HTTP server failed to bind port {HTTP_PORT}: {e}")
            self.httpd = None
            return False
        self.thread = threading.Thread(target=self.httpd.serve_forever, daemon=True)
        self.thread.start()
        self.log(f"HTTP server listening on port {HTTP_PORT}")
        return True

    def stop(self):
        if self.httpd:
            try:
                self.httpd.shutdown()
            except Exception:
                pass
            try:
                self.httpd.server_close()
            except Exception:
                pass
            self.httpd = None
            self.thread = None
            self.log("HTTP server stopped")


class HostsManager:
    def __init__(self, log):
        self.log = log
        self.managed = set()

    def _read(self):
        if not HOSTS_FILE.exists():
            return []
        try:
            return HOSTS_FILE.read_text(encoding="utf-8", errors="ignore").splitlines()
        except OSError as e:
            self.log(f"Could not read hosts file: {e}")
            return []

    def _write(self, lines):
        tmp = HOSTS_FILE.with_suffix(".localnet.tmp")
        try:
            tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
            shutil.move(str(tmp), str(HOSTS_FILE))
            return True
        except PermissionError:
            self.log("Administrator privileges are required to modify the hosts file.")
            try:
                if tmp.exists():
                    tmp.unlink()
            except OSError:
                pass
            return False
        except OSError as e:
            self.log(f"Could not write hosts file: {e}")
            return False

    def add(self, domain):
        lines = self._read()
        for line in lines:
            stripped = line.split("#", 1)[0].strip()
            if not stripped:
                continue
            parts = stripped.split()
            if len(parts) >= 2 and domain in parts[1:]:
                self.log(f"Hosts entry for {domain} already present.")
                return True
        lines.append(f"127.0.0.1 {domain} {MARKER}")
        if not self._write(lines):
            return False
        self.managed.add(domain)
        self.log(f"Added hosts entry: 127.0.0.1 {domain}")
        self._flush_dns()
        return True

    def remove_managed(self):
        lines = self._read()
        new_lines = [ln for ln in lines if MARKER not in ln]
        if len(new_lines) != len(lines):
            if self._write(new_lines):
                self.log("Removed LocalNet-managed hosts entries.")
        self.managed.clear()

    def _flush_dns(self):
        try:
            subprocess.run(["ipconfig", "/flushdns"], capture_output=True, timeout=10)
        except Exception:
            pass


def detect_lan_ip():
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


def port_in_use(port):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.settimeout(0.3)
        return s.connect_ex(("127.0.0.1", port)) == 0
    except Exception:
        return False
    finally:
        s.close()


class LocalNetApp:
    def __init__(self, root):
        self.root = root
        self.logq = LogQueue()
        self.store = SiteStore()
        self.server = Server(self.store, self._log)
        self.hosts = HostsManager(self._log)
        self._build_ui()
        self._log("LocalNet ready. Type 'help' or a command.")
        self._pump()

    def _build_ui(self):
        self.root.title("LocalNet command line")
        self.root.configure(bg="#0c0c0c")
        self.root.geometry("900x560")
        self.output = scrolledtext.ScrolledText(
            self.root, bg="#0c0c0c", fg="#d0d0d0", insertbackground="#d0d0d0",
            font=("Consolas", 10), borderwidth=0, state="disabled"
        )
        self.output.pack(fill=tk.BOTH, expand=True, padx=6, pady=(6, 0))
        bottom = tk.Frame(self.root, bg="#0c0c0c")
        bottom.pack(fill=tk.X, padx=6, pady=6)
        tk.Label(bottom, text=">", bg="#0c0c0c", fg="#4ec9b0",
                 font=("Consolas", 11, "bold")).pack(side=tk.LEFT)
        self.entry = tk.Entry(bottom, bg="#0c0c0c", fg="#ffffff",
                              insertbackground="#ffffff", font=("Consolas", 11),
                              borderwidth=0, highlightthickness=1,
                              highlightbackground="#333333", highlightcolor="#4ec9b0")
        self.entry.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(6, 0))
        self.entry.bind("<Return>", self._on_enter)
        self.entry.focus_set()
        self.root.protocol("WM_DELETE_WINDOW", self._on_close)

    def _log(self, msg):
        self.logq.put(msg)

    def _pump(self):
        self.logq.drain(self.output)
        self.root.after(80, self._pump)

    def _on_enter(self, event):
        cmd = self.entry.get().strip()
        self.entry.delete(0, tk.END)
        if not cmd:
            return
        self._log(f"> {cmd}")
        threading.Thread(target=self._dispatch, args=(cmd,), daemon=True).start()

    def _dispatch(self, cmd):
        parts = cmd.split()
        verb = parts[0].lower()
        args = parts[1:]
        try:
            if verb == "host":
                self._cmd_host(args)
            elif verb == "open":
                self._cmd_open(args)
            elif verb == "restrict":
                self._cmd_restrict(args)
            elif verb == "status":
                self._cmd_status()
            elif verb == "shutdown":
                self._cmd_shutdown()
            elif verb == "help":
                self._cmd_help()
            else:
                self._log(f"Unknown command: {verb}")
        except Exception as e:
            self._log(f"Error: {e}")

    def _require_name(self, args):
        if len(args) != 1:
            self._log("Usage: <command> <name>")
            return None
        name = validate_name(args[0])
        if not name:
            self._log(f"Invalid domain name: {args[0]}")
            return None
        return name

    def _cmd_host(self, args):
        name = self._require_name(args)
        if not name:
            return
        folder = ensure_domain_folder(name)
        self._log(f"Website directory: {folder}")
        if not self.server.running():
            if port_in_use(HTTP_PORT):
                self._log(f"Port {HTTP_PORT} is already in use by another process.")
                return
            if not self.server.start():
                self._log("Hosting failed: HTTP server did not start.")
                return
        self.store.add(name)
        domain = full_domain(name)
        hosts_ok = self.hosts.add(domain)
        if not hosts_ok:
            self._log("Same-PC resolution not configured (hosts file needs admin).")
        lan_ip = detect_lan_ip()
        self._log(f"Hosted: http://{domain}:{HTTP_PORT}")
        self._log(f"LAN URL: http://{lan_ip}:{HTTP_PORT} (Host header required for other devices)")

    def _cmd_open(self, args):
        name = self._require_name(args)
        if not name:
            return
        if name not in self.store.list_hosted():
            self._log(f"Domain '{name}' is not hosted. Use 'host {name}' first.")
            return
        if self.store.is_restricted(name):
            self._log(f"Domain '{name}' is restricted.")
            return
        url = f"http://{full_domain(name)}:{HTTP_PORT}"
        try:
            webbrowser.open(url)
            self._log(f"Opened {url}")
        except Exception as e:
            self._log(f"Could not open browser: {e}")

    def _cmd_restrict(self, args):
        name = self._require_name(args)
        if not name:
            return
        if self.store.restrict(name):
            self._log(f"Domain '{name}' is now restricted.")
        else:
            self._log(f"Domain '{name}' is not hosted.")

    def _cmd_status(self):
        self._log("--- LocalNet status ---")
        self._log(f"HTTP server: {'running' if self.server.running() else 'stopped'} (port {HTTP_PORT})")
        self._log(f"Port {HTTP_PORT} in use: {port_in_use(HTTP_PORT)}")
        self._log(f"Administrator: {is_admin()}")
        self._log(f"LAN IP: {detect_lan_ip()}")
        hosted = self.store.list_hosted()
        self._log(f"Hosted domains: {', '.join(hosted) if hosted else '(none)'}")
        restricted = self.store.list_restricted()
        self._log(f"Restricted domains: {', '.join(restricted) if restricted else '(none)'}")
        self._log("DNS service: not implemented (hosts-file entries only)")
        self._log("Hotspot: not managed by LocalNet")
        if hosted:
            for n in hosted:
                mark = " [restricted]" if n in restricted else ""
                self._log(f"  - http://{full_domain(n)}:{HTTP_PORT}{mark}")

    def _cmd_shutdown(self):
        self.server.stop()
        self.hosts.remove_managed()
        self.store.hosted.clear()
        self.store.restricted.clear()
        self._log("Shutdown complete.")

    def _cmd_help(self):
        self._log("Commands:")
        self._log("  host <name>      Create and host a domain")
        self._log("  open <name>      Open a hosted domain in the browser")
        self._log("  restrict <name>  Block access to a hosted domain")
        self._log("  status           Show service and network status")
        self._log("  shutdown         Stop services and clean up")
        self._log("  help             Show this help")

    def _on_close(self):
        try:
            self.server.stop()
            self.hosts.remove_managed()
        except Exception:
            pass
        self.root.destroy()


def main():
    DOMAINS_DIR.mkdir(parents=True, exist_ok=True)
    root = tk.Tk()
    LocalNetApp(root)
    root.mainloop()


if __name__ == "__main__":
    main()
